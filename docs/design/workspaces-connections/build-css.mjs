// Generates mock.css for the #106 design mockups.
//
//   node docs/design/workspaces-connections/build-css.mjs
//
// mock.css = the real Studio stylesheets (SchoolHouse tokens, kit, hi-fi, theme
// bridge, concatenated verbatim) + role VALUES for two built-in themes read out of
// theme/builtin.ts + mock-additions.css (new components this design proposes and
// the document chrome). Nothing here is shipped product code.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const src = join(here, '../../../studio/frontend/src')
const read = (p) => readFileSync(join(src, p), 'utf8')

// ---- role values from builtin.ts -------------------------------------------
const builtin = read('theme/builtin.ts')
function colorsOf(exportName) {
  const start = builtin.indexOf(`export const ${exportName}`)
  const cs = builtin.indexOf('colors: {', start)
  const end = builtin.indexOf('\n  },', cs)
  const out = []
  for (const m of builtin.slice(cs, end).matchAll(/'([a-z.0-9]+)':\s*'([^']+)'/g)) {
    out.push(`  --vibe-${m[1].replace(/\./g, '-')}: ${m[2]};`)
  }
  return out.join('\n')
}
const FONTS = `  --vibe-font-display: 'Fraunces', Georgia, 'Times New Roman', serif;
  --vibe-font-body: 'Inter', system-ui, -apple-system, sans-serif;
  --vibe-font-mono: 'JetBrains Mono', 'SF Mono', Menlo, monospace;`
const roles =
  `/* ---- role values generated from theme/builtin.ts (docs only) ---- */\n` +
  `:root, :root[data-theme="light"] {\n${colorsOf('SCHOOLHOUSE_LIGHT')}\n${FONTS}\n}\n` +
  `:root[data-theme="dark"] {\n${colorsOf('SCHOOLHOUSE_DARK')}\n}\n`

// bridge.css carries a hex fallback block; drop it, we generate the roles above.
let bridge = read('theme/bridge.css')
const a = bridge.indexOf('/* No-JS / pre-install fallback')
const b = bridge.indexOf('/* ---- Selection + native controls')
bridge = bridge.slice(0, a) + bridge.slice(b)

const fonts = read('fonts.css').replaceAll('./assets/fonts/', '../../../studio/frontend/src/assets/fonts/')
const additions = readFileSync(join(here, 'mock-additions.css'), 'utf8')

const out = [
  '/* GENERATED by build-css.mjs. Do not edit; edit mock-additions.css and re-run. */',
  fonts,
  '/* ===== schoolhouse/colors_and_type.css ===== */', read('schoolhouse/colors_and_type.css'),
  '/* ===== schoolhouse/kit.css ===== */', read('schoolhouse/kit.css'),
  '/* ===== schoolhouse/hifi.css ===== */', read('schoolhouse/hifi.css'),
  '/* ===== theme/bridge.css (fallback block replaced) ===== */', bridge,
  roles,
  '/* ===== mock-additions.css ===== */', additions,
].join('\n')
writeFileSync(join(here, 'mock.css'), out)
console.log('mock.css', out.length, 'bytes')
