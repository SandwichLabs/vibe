// The measure rule rests on two lists generated from DuckDB: every keyword of
// every category (keywords_all.go) and the scalar and aggregate functions a
// measure may call (functions_allow.go). A DuckDB upgrade that changes either
// fails the tests below; regenerate with
//
//	go test ./internal/semantics -run TestGenerateLists -update-lists
var updateLists = flag.Bool("update-lists", false, "rewrite keywords_all.go and functions_allow.go from the linked DuckDB")

// deniedFunction reports whether the generator must leave name out of the
// allow-list: the deny set, internal functions and MotherDuck's.
func deniedFunction(name string) bool {
	return measureDeniedFunctions[name] || strings.HasPrefix(name, "__") || strings.HasPrefix(name, "md_") ||
		strings.HasPrefix(name, "motherduck_") || strings.HasPrefix(name, "duckdb_") || strings.HasPrefix(name, "read_")
}

var plainFunctionRE = regexp.MustCompile(`^[a-z_][a-z0-9_]*$`)

func liveSet(t *testing.T, query string) map[string]bool {
	t.Helper()
	db, err := sql.Open("duckdb", "")
	require.NoError(t, err)
	defer db.Close()
	rows, err := db.Query(query)
	require.NoError(t, err)
	defer rows.Close()
	out := map[string]bool{}
	for rows.Next() {
		var n string
		require.NoError(t, rows.Scan(&n))
		out[n] = true
	}
	require.NoError(t, rows.Err())
	return out
}

func liveAllKeywords(t *testing.T) map[string]bool {
	return liveSet(t, "SELECT keyword_name FROM duckdb_keywords()")
}

func liveAllowedFunctions(t *testing.T) map[string]bool {
	live := liveSet(t, "SELECT DISTINCT function_name FROM duckdb_functions() WHERE function_type IN ('aggregate', 'scalar')")
	out := map[string]bool{}
	for n := range live {
		if plainFunctionRE.MatchString(n) && !deniedFunction(n) {
			out[n] = true
		}
	}
	return out
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func writeList(t *testing.T, file, name, doc string, set map[string]bool) {
	var b strings.Builder
	b.WriteString("package semantics\n\n// Code generated by `go test ./internal/semantics -run TestGenerateLists -update-lists`; DO NOT EDIT.\n\n")
	b.WriteString(doc + "\nvar " + name + " = setOf(\n")
	line := "\t"
	for _, k := range sortedKeys(set) {
		item := fmt.Sprintf("%q, ", k)
		if len(line)+len(item) > 110 {
			b.WriteString(strings.TrimRight(line, " ") + "\n")
			line = "\t"
		}
		line += item
	}
	b.WriteString(strings.TrimRight(line, " ") + "\n)\n")
	require.NoError(t, os.WriteFile(file, []byte(b.String()), 0o644))
}

func TestGenerateLists(t *testing.T) {
	if !*updateLists {
		t.Skip("run with -update-lists to regenerate keywords_all.go and functions_allow.go")
	}
	writeList(t, "keywords_all.go", "allKeywords", "// allKeywords is every keyword_name of duckdb_keywords(), in every category.", liveAllKeywords(t))
	writeList(t, "functions_allow.go", "allowedFunctions", "// allowedFunctions is DuckDB's scalar and aggregate functions less measureDeniedFunctions.", liveAllowedFunctions(t))
}

func TestAllKeywordsMatchDuckDB(t *testing.T) {
	assert.Equal(t, liveAllKeywords(t), allKeywords, "regenerate with -update-lists")
	for k := range reservedKeywords {
		assert.True(t, allKeywords[k], "reserved %q is a keyword", k)
	}
}

func TestAllowedFunctionsMatchDuckDB(t *testing.T) {
	assert.Equal(t, liveAllowedFunctions(t), allowedFunctions, "regenerate with -update-lists")
	for _, f := range []string{"sum", "count", "avg", "min", "max", "date_trunc", "round", "string_agg", "approx_count_distinct"} {
		assert.True(t, allowedFunctions[f], f)
	}
	for f := range syntaxFunctions {
		assert.True(t, allKeywords[f], "%s is keyword syntax", f)
		assert.False(t, allowedFunctions[f], "%s is not in duckdb_functions()", f)
	}
	for _, f := range []string{"getenv", "query", "read_csv", "read_text", "nextval", "current_setting", "columns", "unnest", "metric", "which_secret"} {
		assert.False(t, allowedFunctions[f], f)
	}
}
