// currentSchemaVersion is the latest schema version for the .vibe format.
const currentSchemaVersion = "1"

// schemaDDL contains the CREATE TABLE statements for all _vibe_* tables.
var schemaDDL = []string{
	`CREATE TABLE IF NOT EXISTS _vibe_meta (
		key   TEXT PRIMARY KEY,
		value TEXT NOT NULL
	);`,

	`CREATE TABLE IF NOT EXISTS _vibe_pages (
		id         TEXT PRIMARY KEY,
		title      TEXT NOT NULL DEFAULT '',
		content    TEXT NOT NULL DEFAULT '',
		page_type  TEXT NOT NULL DEFAULT 'markdown',
		sort_order INTEGER NOT NULL DEFAULT 0,
		created_at TEXT NOT NULL,
		updated_at TEXT NOT NULL,
		metadata   TEXT NOT NULL DEFAULT '{}'
	);`,

	`CREATE TABLE IF NOT EXISTS _vibe_queries (
		id         TEXT PRIMARY KEY,
		title      TEXT NOT NULL DEFAULT '',
		sql        TEXT NOT NULL DEFAULT '',
		engine     TEXT NOT NULL DEFAULT 'duckdb',
		parameters TEXT NOT NULL DEFAULT '{}',
		created_at TEXT NOT NULL,
		updated_at TEXT NOT NULL
	);`,

	`CREATE TABLE IF NOT EXISTS _vibe_components (
		id         TEXT PRIMARY KEY,
		type       TEXT NOT NULL DEFAULT '',
		config     TEXT NOT NULL DEFAULT '{}',
		created_at TEXT NOT NULL
	);`,

	`CREATE TABLE IF NOT EXISTS _vibe_agent_config (
		key   TEXT PRIMARY KEY,
		value TEXT NOT NULL
	);`,

	`CREATE TABLE IF NOT EXISTS _vibe_secrets (
		id         TEXT PRIMARY KEY,
		name       TEXT NOT NULL DEFAULT '',
		value      TEXT NOT NULL DEFAULT '',
		created_at TEXT NOT NULL
	);`,

	`CREATE TABLE IF NOT EXISTS _vibe_assets (
		id         TEXT PRIMARY KEY,
		filename   TEXT NOT NULL DEFAULT '',
		mime_type  TEXT NOT NULL DEFAULT 'application/octet-stream',
		data       BLOB,
		created_at TEXT NOT NULL
	);`,

	`CREATE TABLE IF NOT EXISTS _vibe_duckdb (
		id      INTEGER PRIMARY KEY CHECK(id = 1),
		data    BLOB NOT NULL,
		updated TEXT NOT NULL
	);`,

	// _vibe_skills stores Skills (#62): SKILL.md-style domain context the agent
	// (in-app wizard and external MCP clients) can load on demand via
	// read_skill. name is the routing key advertised in the system prompt's
	// <skills> block (progressive disclosure — only description ships there;
	// instructions load lazily). table_name, when set, gates the skill so it
	// only loads once that table exists and has at least one row (see
	// internal/agents.LoadSkills) — used by the import wizard's generated
	// workspace-<table> skills. source distinguishes a hand-authored skill
	// ('user') from one generated by the import wizard ('import'); built-in
	// skills are embedded in the binary (internal/llm/skills) and never rows
	// here. Additive migration.
	`CREATE TABLE IF NOT EXISTS _vibe_skills (
		name         TEXT PRIMARY KEY,
		description  TEXT NOT NULL DEFAULT '',
		instructions TEXT NOT NULL DEFAULT '',
		table_name   TEXT NOT NULL DEFAULT '',
		source       TEXT NOT NULL DEFAULT 'user',
		created_at   TEXT NOT NULL DEFAULT '',
		updated_at   TEXT NOT NULL DEFAULT ''
	);`,

	// _vibe_field_meta, _vibe_forms, _vibe_relationships, _vibe_reports,
	// _vibe_nav, and _vibe_macros (the Access application layer: bound
	// forms/subforms, field metadata, the relationships UI, banded reports,
	// the switchboard, and macros) are REMOVED (#68). Vibe is an agentic data
	// exploration tool, not a form builder; datasheet editing (internal/crud)
	// stays. Per the additive-migration policy, these CREATE TABLE statements
	// are simply no longer run — an OLD file that already has these tables
	// keeps them untouched (never dropped), and `vibe verify` no longer
	// requires them. _vibe_reports rows are migrated into notebooks once
	// (see studio's migrateReportsToNotebooks) the first time such a file is
	// opened after upgrading.

	// _vibe_notebooks stores Notebooks (#66): a title plus a JSON array of
	// cells (sql / markdown / a2ui — internal/notebooks.Cell). Every load
	// goes through internal/notebooks.Coerce, a whitelist rebuild, so this
	// table is never trusted to already hold a well-formed document — a row
	// here could be a future schema version, a hand-edited file, or a bug.
	// Cell OUTPUTS are never stored: only source/view/page, never a query
	// result. Additive migration.
	`CREATE TABLE IF NOT EXISTS _vibe_notebooks (
		id         TEXT PRIMARY KEY,
		title      TEXT NOT NULL DEFAULT '',
		cells      TEXT NOT NULL DEFAULT '[]',
		created_at TEXT NOT NULL DEFAULT '',
		updated_at TEXT NOT NULL DEFAULT ''
	);`,
}

// defaultMeta contains the default metadata entries seeded on creation.
var defaultMeta = map[string]string{
	"schema_version": currentSchemaVersion,
	"format_version": "1.0",
	"created_at":     "", // set at runtime
	"updated_at":     "", // set at runtime
	"title":          "",
	"description":    "",
	// The in-app wizard agent is the "wizard layer" meant to build schema, so
	// it defaults to full write access. Users can restrict it via
	// SetAgentConfig.
	"agent_sandbox": "full",
	// Note: LLM provider/model/endpoint are app-global and viper-driven
	// (~/.vibe.yaml + VIBE_LLM_* env), not per-file. Only the agent sandbox above
	// is a per-.vibe setting.
}

// ensureColumn applies an additive ADD COLUMN migration if (and only if) the
// column is missing, so re-running migrations on any file vintage is a no-op.
func ensureColumn(tx *sql.Tx, table, column, ddl string) error {
	var n int
	if err := tx.QueryRow(
		`SELECT COUNT(*) FROM pragma_table_info(?) WHERE name = ?`, table, column,
	).Scan(&n); err != nil {
		return fmt.Errorf("failed to inspect %s.%s: %w", table, column, err)
	}
	if n > 0 {
		return nil
	}
	if _, err := tx.Exec(ddl); err != nil {
		return fmt.Errorf("failed to add column %s.%s: %w", table, column, err)
	}
	return nil
}

// runMigrations creates all _vibe_* tables and seeds default metadata.
func runMigrations(db *sql.DB) error {
	tx, err := db.Begin()
	if err != nil {
		return fmt.Errorf("failed to begin migration transaction: %w", err)
	}
	defer tx.Rollback() //nolint:errcheck

	for _, ddl := range schemaDDL {
		if _, err := tx.Exec(ddl); err != nil {
			return fmt.Errorf("failed to execute DDL: %w", err)
		}
	}

	// Additive column migrations for tables that predate a column (CREATE TABLE
	// IF NOT EXISTS does not reshape an existing table).
	for _, m := range []struct{ table, column, ddl string }{
		// #66 part A: pages migrate to notebooks idempotently. migrated_to
		// holds the id of the notebook a page became, or '' if not yet
		// migrated (or never migrated — a page is never deleted by this).
		{"_vibe_pages", "migrated_to", `ALTER TABLE _vibe_pages ADD COLUMN migrated_to TEXT NOT NULL DEFAULT ''`},
	} {
		if err := ensureColumn(tx, m.table, m.column, m.ddl); err != nil {
			return err
		}
	}

	if err := tx.Commit(); err != nil {
		return fmt.Errorf("failed to commit migration transaction: %w", err)
	}

	return nil
}

// seedMeta inserts default metadata entries if they do not already exist.
func seedMeta(db *sql.DB, title, description string) error {
	now := time.Now().UTC().Format(time.RFC3339)

	tx, err := db.Begin()
	if err != nil {
		return fmt.Errorf("failed to begin seed transaction: %w", err)
	}
	defer tx.Rollback() //nolint:errcheck

	for key, value := range defaultMeta {
		switch key {
		case "created_at", "updated_at":
			value = now
		case "title":
			if title != "" {
				value = title
			}
		case "description":
			if description != "" {
				value = description
			}
		}

		_, err := tx.Exec(
			"INSERT OR IGNORE INTO _vibe_meta (key, value) VALUES (?, ?);",
			key, value,
		)
		if err != nil {
			return fmt.Errorf("failed to seed meta key %q: %w", key, err)
		}
	}

	if err := tx.Commit(); err != nil {
		return fmt.Errorf("failed to commit seed transaction: %w", err)
	}

	return nil
}
